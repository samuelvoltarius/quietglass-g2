const ALIASES: Readonly<Record<string, string>> = { "–": "-", "—": "-", "−": "-", "±": "+-", "•": "·", "ß": "SS" };

/** The characters the pixel font draws for `text`: upper case, diacritics dropped. */
export function pixelChars(text: string): string[] {
  const out: string[] = [];
  for (const raw of Array.from(text)) {
    const aliased = ALIASES[raw] ?? raw;
    for (const char of Array.from(aliased.length > 1 ? aliased : aliased.normalize("NFD").replace(/[̀-ͯ]/g, "").toUpperCase())) out.push(char);
  }
  return out;
}

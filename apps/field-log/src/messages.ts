export function t(locale: Locale, key: string, vars: Record<string, string | number> = {}): string {
  return tr(messages, locale, key, vars);
}

export function severityName(locale: Locale, severity: Severity): string {
  return t(locale, "sev." + severity);
}

/** The quick notes offered on the glasses: the user's own list, or the defaults. */
export function quickNotes(locale: Locale, custom: readonly string[]): string[] {
  const own = custom.map((note) => note.trim()).filter(Boolean);
  return own.length > 0 ? own : t(locale, "quick.defaults").split("\n");
}

/** Title for an inspection started without a name, e.g. "Rundgang 6.10., 14:05". */
export function autoTitle(locale: Locale, now: number): string {
  const date = new Date(now).toLocaleString(locale === "de" ? "de-AT" : "en-GB", {
    day: "numeric", month: "numeric", hour: "2-digit", minute: "2-digit",
  });
  return t(locale, "autoTitle", { date });
}

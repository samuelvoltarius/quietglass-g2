import { describe, expect, it } from "vitest";
import { parseSetupQr } from "../src/setup/qr";

describe("Quiet Hub setup QR", () => {
  it("reads the server and token generated by the Pi start command", () => {
    expect(parseSetupQr("http://pi5:5210/#server=http%3A%2F%2F100.64.0.5%3A8787&token=secret", true)).toEqual({
      serverUrl: "http://100.64.0.5:8787",
      token: "secret",
      autoOpenNotifications: true,
    });
  });

  it("rejects unrelated QR codes", () => {
    expect(() => parseSetupQr("https://example.com", true)).toThrow(/Quiet Hub server/);
  });
});

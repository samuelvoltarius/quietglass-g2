export function t(locale: Locale, key: string, vars: Record<string, string | number> = {}): string {
  return tr(messages, locale, key, vars);
}

/**
 * The errors this app produces itself are kept in English inside the state
 * (tests, logs and the CORS hint match on them) and translated only when they
 * are shown. Anything else — a message a server sent back — is shown as is.
 */
const ERROR_KEYS: Readonly<Record<string, string>> = Object.fromEntries(
  Object.entries(messages.en)
    .filter(([key]) => key.startsWith("e."))
    .map(([key, english]) => [english, key]),
);

export function localizeError(error: string, locale: Locale): string {
  const key = ERROR_KEYS[error];
  return key ? t(locale, key) : error;
}

export const SAMPLE_SCRIPT_TITLE = "How PromptFlow works";

export const SAMPLE_SCRIPT_SOURCE = `# How PromptFlow works

This is a sample script. Read it out loud to see how the pacing feels, then
replace it with your own.

## Starting and stopping

Tap once to start scrolling. Tap again to pause. That is the whole transport:
one gesture, and it never moves your position.

## Adjusting the speed

While the script is scrolling, swipe to change the pace by ten words a minute.
Your place on the page stays exactly where it is, because losing your line
mid-sentence is worse than a slightly wrong speed.

## Moving around

While paused, swiping moves you through the script instead. Hold to jump to the
next section. Double tap to leave.

## Sections

Every heading like the ones in this script becomes a section, shown in the
corner so you always know where you are.
`;
